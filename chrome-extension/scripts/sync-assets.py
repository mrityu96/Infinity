#!/usr/bin/env python3
"""Copy the CML Tool UI into the Chrome extension package.

The HTML, CSS, JavaScript, and images under chrome-extension/ that come from
main/ are generated. Edit the sources in main/templates and main/assets, then
re-run this script. Do not hand-edit the copied files.
"""

from __future__ import annotations

import shutil
import sys
from pathlib import Path


EXTENSION_ROOT = Path(__file__).resolve().parents[1]
PROJECT_ROOT = EXTENSION_ROOT.parent
MAIN_ROOT = PROJECT_ROOT / "main"
TEMPLATE = MAIN_ROOT / "templates" / "index.html"
ASSETS = MAIN_ROOT / "assets"
FAVICON = MAIN_ROOT / "favicon"
DONATE = MAIN_ROOT / "donate"

RUNTIME_SCRIPT = (
    '<script src="/assets/js/theme-init.js"></script>\n'
    '<script src="/runtime-config.js"></script>'
)
OVERLAY_SCRIPT = (
    '<script src="/assets/js/api-client.js" defer></script>\n'
    '<script src="/offline-overlay.js" defer></script>'
)
GENERATED_BANNER = (
    "<!-- Generated by chrome-extension/scripts/sync-assets.py. "
    "Edit main/templates/index.html instead. -->\n"
)


def _copytree(source: Path, destination: Path) -> None:
    if destination.exists():
        shutil.rmtree(destination)
    shutil.copytree(
        source,
        destination,
        ignore=shutil.ignore_patterns(".DS_Store", "Thumbs.db"),
    )


def _transform_html(text: str) -> str:
    html = text
    html = html.replace(
        '<meta name="cml-csrf-token" content="__CML_CSRF_TOKEN__" />\n',
        "",
    )
    if '<script src="/runtime-config.js"></script>' not in html:
        if '<script src="/assets/js/theme-init.js"></script>' not in html:
            raise SystemExit("index.html is missing theme-init.js")
        html = html.replace(
            '<script src="/assets/js/theme-init.js"></script>',
            RUNTIME_SCRIPT,
        )
    if '<script src="/offline-overlay.js" defer></script>' not in html:
        if '<script src="/assets/js/api-client.js" defer></script>' not in html:
            raise SystemExit("index.html is missing api-client.js")
        html = html.replace(
            '<script src="/assets/js/api-client.js" defer></script>',
            OVERLAY_SCRIPT,
        )
    if not html.startswith(GENERATED_BANNER):
        html = GENERATED_BANNER + html
    return html


def main() -> int:
    if not TEMPLATE.is_file():
        print("Missing template:", TEMPLATE, file=sys.stderr)
        return 1
    (EXTENSION_ROOT / "index.html").write_text(
        _transform_html(TEMPLATE.read_text(encoding="utf-8")),
        encoding="utf-8",
    )
    _copytree(ASSETS, EXTENSION_ROOT / "assets")
    _copytree(FAVICON, EXTENSION_ROOT / "favicon")
    _copytree(DONATE, EXTENSION_ROOT / "donate")
    icons = EXTENSION_ROOT / "icons"
    icons.mkdir(exist_ok=True)
    shutil.copyfile(FAVICON / "favicon-96x96.png", icons / "icon-96.png")
    shutil.copyfile(
        FAVICON / "web-app-manifest-192x192.png", icons / "icon-192.png")
    print("Synced CML Tool UI into", EXTENSION_ROOT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
